/**
 * Arché · Pilgrim Private: app-shell service worker (Offline Phase 5).
 *
 * Purpose: let the app OPEN with no signal (app closed, airplane mode, tap the icon).
 * Scope: /pilgrim-private/ only. It never touches Scribe, Pilgrim Public or any other folder.
 *
 * What it caches
 *   - The app shell: index.html, every ES module at its exact ?v= URL, manifest, icons, self-hosted vendor libs.
 *     Cache name: pilgrim-shell-<VERSION>. Filled all-or-nothing at install (one failure = install fails, old worker stays).
 *   - Google Fonts (CSS + files), stale-while-revalidate, in pilgrim-fonts (survives version changes).
 *
 * What it NEVER touches (the browser handles these as if no worker existed)
 *   - /data/* (offline packs use their own fetch + IndexedDB), /auth/* and every Worker/API call,
 *     bolls.life, bible-api.com, the pdf.js CDN, and any non-navigation request with cache:'no-store' or a ?t=
 *     parameter (so the update check sees the real server). Page navigations, including reloads, are always answered.
 *
 * Updates: a new worker installs in the background and WAITS. The page shows the "Update ready" banner; Refresh Now
 * posts SKIP_WAITING. There is no skipWaiting at install.
 *
 * Kill switch (layer 2 of 3): on each navigation the worker fetches sw-kill.json in the background (short timeout,
 * failures ignored). {"kill":true} makes it delete the pilgrim-shell-* caches and unregister itself.
 * It never touches IndexedDB, localStorage, studies, backups or any other app's caches.
 *
 * The PRECACHE list and VERSION below are generated by tests/gen-precache.js and enforced by tests/release-check.js.
 */
'use strict';

/* VERSION:BEGIN */
const VERSION = '4.69.0';
/* VERSION:END */
/* PRECACHE:BEGIN */
const PRECACHE = [
  'app.js?v=4.69.0',
  'icons/icon-192.png',
  'icons/icon-512-maskable.png',
  'icons/icon-512.png',
  'index.html',
  'manifest.json',
  'media.js?v=4.69.0',
  'memory-core.js?v=4.69.0',
  'memory.js?v=4.69.0',
  'morph.js?v=4.69.0',
  'offline.js?v=4.69.0',
  'readingplan-core.js?v=4.69.0',
  'readingplan-data.js?v=4.69.0',
  'readingplan.js?v=4.69.0',
  'shell.js?v=4.69.0',
  'storage.js?v=4.69.0',
  'studyTools.js?v=4.69.0',
  'sync.js?v=4.69.0',
  'tts.js?v=4.69.0',
  'ui.js?v=4.69.0',
  'utils.js?v=4.69.0',
  'vendor/jspdf.umd.min.js',
  'vendor/mammoth.browser.min.js',
  'vendor/purify.min.js',
  'vendor/quill.min.js',
  'vendor/quill.snow.css',
  'versemap.js?v=4.69.0'
];
/* PRECACHE:END */

const SHELL_PREFIX = 'pilgrim-shell-';
const SHELL_CACHE = SHELL_PREFIX + VERSION;
const FONT_CACHE = 'pilgrim-fonts';
const FONT_HOSTS = ['fonts.googleapis.com', 'fonts.gstatic.com'];
const KILL_URL = new URL('sw-kill.json', self.registration.scope).href;
const KILL_TIMEOUT_MS = 3000;

/** Absolute URL for a precache entry (entries are relative to the worker's scope). */
function abs(rel) { return new URL(rel, self.registration.scope).href; }

/**
 * Install: precache the whole shell, all-or-nothing. Requests bypass the HTTP cache so a half-stale CDN copy
 * can never be frozen into a release's cache. Does NOT call skipWaiting (the update banner decides when).
 * @param {ExtendableEvent} e
 */
self.addEventListener('install', function (e) {
  e.waitUntil(
    caches.open(SHELL_CACHE).then(function (cache) {
      return Promise.all(PRECACHE.map(function (rel) {
        return fetch(new Request(abs(rel), { cache: 'reload' })).then(function (res) {
          if (!res.ok) { throw new Error('precache failed ' + res.status + ' ' + rel); }
          return cache.put(abs(rel), res);
        });
      }));
    })
  );
});

/**
 * Activate: drop every older pilgrim-shell-* cache (never pilgrim-fonts, never another app's cache), then take control.
 * @param {ExtendableEvent} e
 */
self.addEventListener('activate', function (e) {
  e.waitUntil(
    caches.keys().then(function (names) {
      return Promise.all(names.filter(function (n) {
        return n.indexOf(SHELL_PREFIX) === 0 && n !== SHELL_CACHE;
      }).map(function (n) { return caches.delete(n); }));
    }).then(function () { return self.clients.claim(); })
  );
});

/**
 * Messages from the page. SKIP_WAITING activates a waiting worker (Refresh Now). GET_VERSION replies with VERSION.
 * @param {ExtendableMessageEvent} e
 */
self.addEventListener('message', function (e) {
  var d = e.data || {};
  if (d.type === 'SKIP_WAITING') { self.skipWaiting(); }
  else if (d.type === 'GET_VERSION' && e.source) { e.source.postMessage({ type: 'VERSION', version: VERSION }); }
});

/**
 * Kill-switch layer 2: look at sw-kill.json (network only, short timeout, failures ignored).
 * If {"kill":true}: delete pilgrim-shell-* caches and unregister. IndexedDB and localStorage are never touched.
 * @returns {Promise<void>}
 */
function checkKill() {
  var ctl = ('AbortController' in self) ? new AbortController() : null;
  var timer = ctl ? setTimeout(function () { ctl.abort(); }, KILL_TIMEOUT_MS) : null;
  return fetch(new Request(KILL_URL + '?t=' + Date.now(), { cache: 'no-store', signal: ctl ? ctl.signal : undefined }))
    .then(function (r) { return r.ok ? r.json() : null; })
    .then(function (j) {
      if (!j || j.kill !== true) { return; }
      return caches.keys().then(function (names) {
        return Promise.all(names.filter(function (n) { return n.indexOf(SHELL_PREFIX) === 0; })
          .map(function (n) { return caches.delete(n); }));
      }).then(function () { return self.registration.unregister(); });
    })
    .catch(function () { /* offline or bad JSON: ignore, never block the app */ })
    .then(function () { if (timer) { clearTimeout(timer); } });
}

/**
 * True for requests that must go straight to the network (never intercepted).
 * @param {Request} req
 * @param {URL} url
 */
function bypass(req, url) {
  if (req.method !== 'GET') { return true; }
  // Cache mode 'reload' is NOT a reason to bypass: Chrome marks a normal reload (and pull-to-refresh) of the page, and
  // the files it loads, as cache:'reload', and the app must still open from the cache with no signal.
  // Only an explicit no-store fetch or a ?t= cache-buster (the app's own update checks) goes to the real server.
  if (req.mode === 'navigate') { return false; }
  if (req.cache === 'no-store') { return true; }
  if (url.searchParams.has('t')) { return true; }
  return false;
}

/**
 * Fetch routing. Only three things are ever answered by the worker:
 *   1. navigations inside the scope  -> cached index.html (network first when the URL carries ?fresh=, for Force refresh)
 *   2. same-origin GETs whose exact URL is in the precache -> cache first, network on a miss (not stored)
 *   3. Google Fonts -> stale-while-revalidate in pilgrim-fonts
 * Everything else returns without respondWith, i.e. the browser's normal behavior.
 * @param {FetchEvent} e
 */
self.addEventListener('fetch', function (e) {
  var req = e.request;
  var url = new URL(req.url);
  if (bypass(req, url)) { return; }

  if (FONT_HOSTS.indexOf(url.hostname) !== -1) {
    e.respondWith(fontsSWR(req));
    return;
  }

  if (url.origin !== self.location.origin) { return; }

  if (req.mode === 'navigate' && url.href.indexOf(self.registration.scope) === 0) {
    e.waitUntil(checkKill());
    e.respondWith(navigationResponse(req, url));
    return;
  }

  var key = url.origin + url.pathname + url.search;
  if (PRECACHE.some(function (rel) { return abs(rel) === key; })) {
    e.respondWith(
      caches.match(key, { cacheName: SHELL_CACHE }).then(function (hit) {   // match() never creates the cache (open() would, after a kill)
        return hit || fetch(req);
      })
    );
  }
});

/**
 * Answer a navigation: the cached index.html. With ?fresh= (About > Force refresh) try the network first so the
 * person really gets the newest page, falling back to the cache when offline.
 * @param {Request} req
 * @param {URL} url
 * @returns {Promise<Response>}
 */
function navigationResponse(req, url) {
  var shellIndex = abs('index.html');
  var fromCache = function () {
    return caches.match(shellIndex, { cacheName: SHELL_CACHE });
  };
  if (url.searchParams.has('fresh')) {
    return fetch(req).catch(function () { return fromCache().then(function (r) { return r || Response.error(); }); });
  }
  return fromCache().then(function (hit) { return hit || fetch(req); });
}

/**
 * Google Fonts: serve the cached copy at once and refresh it in the background; first use goes to the network.
 * Opaque (no-cors) responses are accepted for the CSS file.
 * @param {Request} req
 * @returns {Promise<Response>}
 */
function fontsSWR(req) {
  return caches.open(FONT_CACHE).then(function (cache) {
    return cache.match(req).then(function (hit) {
      var net = fetch(req).then(function (res) {
        if (res && (res.ok || res.type === 'opaque')) { cache.put(req, res.clone()); }
        return res;
      });
      if (hit) { net.catch(function () {}); return hit; }
      return net;
    });
  });
}
