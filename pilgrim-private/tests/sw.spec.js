// tests/sw.spec.js — Pilgrim Private offline app shell (service worker), Offline Phase 5 (v4.69.0)
//
// Pins the behavior Boss's phone depends on. Each test serves a THROWAWAY COPY of pilgrim-private/ from its own tiny
// Node server (so a test can "ship a new release", flip the kill flag, or stop the server to simulate no signal), in a
// fresh browser context. Nothing here touches a real site; localhost only; all other network is blocked.
//
//   1. Install, then with the server STOPPED the app still opens (reload, and a fresh visit to /), the Quill editor and
//      a downloaded chapter work, the shell cache holds the whole precache list, and first install does not reload the page.
//   2. Update: a new release installs in the background and WAITS, the banner appears, Refresh Now activates it and the page
//      reloads exactly once on the new version, and the old shell cache is deleted. Skip keeps the banner away for that version.
//   3. Kill flag {"kill":true}: worker and shell caches go, but IndexedDB packs, localStorage, pilgrim-fonts and other
//      apps' caches are untouched; setting it back to false lets the app register again.
//   4. Kill layer 2 (inside the worker): even when the page cannot read the flag, the worker removes itself on a navigation.
//   5. Settings "Offline app" switch: Turn off removes the worker + shell caches and stays off across reloads; Turn on restores it.
//   6. Boot cleanup removes only the legacy cache and leaves our shell, pilgrim-fonts and another app's worker/caches alone.
//   7. A fresh PIN entry with no connection says why, in plain words.
//
// Run from pilgrim-private/ (needs @playwright/test; in Claude's sandbox PW_CHROMIUM + NODE_PATH, see gate.js):
//   npx playwright test tests/sw.spec.js      (it starts its own servers; PILGRIM_BASE_URL is not used)

'use strict';

const { test, expect } = require('@playwright/test');
const http = require('http');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const SRC = path.join(__dirname, '..');
const NOISE = /Failed to load resource|ERR_FAILED|ERR_BLOCKED|ERR_TUNNEL|ERR_INTERNET|ERR_CONNECTION|net::/i;
const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.json': 'application/json', '.css': 'text/css', '.png': 'image/png', '.svg': 'image/svg+xml' };

/** Copies the app (no tests, no node_modules) into a temp folder and returns its path. gen-precache.js is copied so a "new release" can be built. */
function copyApp() {
  const dest = fs.mkdtempSync(path.join(os.tmpdir(), 'pilgrim-sw-'));
  fs.cpSync(SRC, dest, { recursive: true, filter: s => !/[\\/](node_modules|test-results|tests)$/.test(s) });
  fs.mkdirSync(path.join(dest, 'tests'));
  fs.copyFileSync(path.join(SRC, 'tests', 'gen-precache.js'), path.join(dest, 'tests', 'gen-precache.js'));
  fs.mkdirSync(path.join(dest, 'scribe'));
  fs.writeFileSync(path.join(dest, 'scribe', 'sw.js'), '// stand-in for another app\'s worker\n');
  return dest;
}

/** A static server for one app copy. stop() drops every connection (= no signal); start() brings it back on the SAME port. */
function makeServer(root) {
  let srv = null;
  let port = 0;
  const handler = (req, res) => {
    const u = new URL(req.url, 'http://x');
    let p = decodeURIComponent(u.pathname);
    if (p.endsWith('/')) p += 'index.html';
    const f = path.join(root, p);
    if (!f.startsWith(root) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { res.writeHead(404); res.end('not found'); return; }
    // Like GitHub Pages: files may be reused from the browser's HTTP cache for 10 minutes. The worker must not be fooled by that.
    res.writeHead(200, { 'Content-Type': MIME[path.extname(f)] || 'application/octet-stream', 'Cache-Control': 'max-age=600' });
    res.end(fs.readFileSync(f));
  };
  return {
    root,
    get origin() { return 'http://127.0.0.1:' + port; },
    start() {
      return new Promise((resolve, reject) => {
        srv = http.createServer(handler);
        srv.once('error', reject);
        srv.listen(port, '127.0.0.1', () => { port = srv.address().port; resolve(); });
      });
    },
    stop() {
      return new Promise(resolve => { if (!srv) return resolve(); srv.closeAllConnections(); srv.close(() => resolve()); srv = null; });
    },
  };
}

/** Rewrites the copied app as a NEW release (next patch version everywhere, sw.js regenerated by the real generator). */
function shipNewRelease(root) {
  const cur = fs.readFileSync(path.join(root, 'sw.js'), 'utf8').match(/const VERSION = '([^']+)'/)[1];
  const [a, b, c] = cur.split('.').map(Number);
  const next = a + '.' + b + '.' + (c + 1);
  fs.readdirSync(root).filter(f => /\.(js|html)$/.test(f) && f !== 'sw.js').forEach(f => {
    const full = path.join(root, f);
    let t = fs.readFileSync(full, 'utf8');
    t = t.split('?v=' + cur).join('?v=' + next);
    if (f === 'utils.js') t = t.replace(new RegExp('(var CHANGELOG=\\[\\s*\\{\\s*version:\\s*\')' + cur.replace(/\./g, '\\.') + '\''), '$1' + next + '\'');
    fs.writeFileSync(full, t);
  });
  const r = spawnSync('node', [path.join(root, 'tests', 'gen-precache.js')], { cwd: root, encoding: 'utf8' });
  if (r.status !== 0) throw new Error('gen-precache failed: ' + r.stdout + r.stderr);
  return { cur, next };
}

const precacheCount = root => (fs.readFileSync(path.join(root, 'sw.js'), 'utf8').match(/PRECACHE = \[([\s\S]*?)\];/)[1].match(/'[^']+'/g) || []).length;
const versionOf = root => fs.readFileSync(path.join(root, 'sw.js'), 'utf8').match(/const VERSION = '([^']+)'/)[1];

let env = null; // { server, ctx, page, errors, root }

test.afterEach(async () => {
  if (!env) return;
  try { await env.ctx.close(); } catch (e) { /* ignore */ }
  await env.server.stop();
  fs.rmSync(env.root, { recursive: true, force: true });
  env = null;
});

/** Starts a server and opens the app as the cached user qa-local (or a fresh visitor with {pin:true}). */
async function open(browser, opts) {
  opts = opts || {};
  const root = copyApp();
  const server = makeServer(root);
  await server.start();
  const ctx = await browser.newContext({ viewport: { width: 390, height: 780 }, baseURL: server.origin });
  if (!opts.pin) {
    await ctx.addInitScript(() => {
      if (!localStorage.getItem('bsn_active_user')) localStorage.setItem('bsn_active_user', 'qa-local');
      localStorage.setItem('bsn_tour_settings_seen_qa-local', '1');
    });
  }
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push('pageerror: ' + e.message));
  page.on('console', m => { if (m.type() === 'error' && !NOISE.test(m.text())) errors.push('console.error: ' + m.text()); });
  page.on('dialog', d => d.accept());
  await ctx.route(u => new URL(u.href).origin !== server.origin, r => r.abort());
  env = { server, ctx, page, errors, root };
  return env;
}

/** Waits for the library screen and removes first-run overlays. */
async function ready(page) {
  await page.waitForFunction(() => document.getElementById('scr-library') && document.getElementById('scr-library').classList.contains('on'), null, { timeout: 15000 });
  await page.evaluate(() => { ['ai-lockdown-overlay', 'ob-overlay', 'tour-offer-overlay'].forEach(i => { const o = document.getElementById(i); if (o) o.remove(); }); });
}

/** Waits until our worker is active AND controls this page. */
async function controlled(page) {
  await page.waitForFunction(() => navigator.serviceWorker && navigator.serviceWorker.controller && /\/sw\.js$/.test(navigator.serviceWorker.controller.scriptURL), null, { timeout: 20000 });
}

const cacheNames = page => page.evaluate(() => caches.keys());
const shellCaches = page => page.evaluate(() => caches.keys().then(k => k.filter(n => n.indexOf('pilgrim-shell-') === 0)));
const regCount = page => page.evaluate(() => navigator.serviceWorker.getRegistrations().then(r => r.length));

/** Installs a tiny FAKE kjv pack (invented words) through the app's own installer. */
function installFake(page) {
  return page.evaluate(() => {
    const john3 = [];
    for (let v = 1; v <= 20; v++) john3.push({ verse: v, text: 'zz-john-' + v });
    return window.offlineInstallPack({ id: 'bible-kjv', name: 'Fake KJV', version: '1', license: 'Test only' }, [['43:3', john3]]);
  });
}

test.describe('Pilgrim Private: offline app shell (service worker), throwaway server per test', () => {
  test.setTimeout(90000);

  test('installs, then the app opens with the server gone: shell, Quill editor and a downloaded chapter', async ({ browser }) => {
    const { page, server, errors, root } = await open(browser);
    let navs = 0;
    page.on('framenavigated', f => { if (f === page.mainFrame()) navs++; });
    await page.goto('/index.html');
    await ready(page);
    await controlled(page);
    await installFake(page);
    // the whole precache list is in this release's shell cache
    const v = versionOf(root);
    expect(await shellCaches(page)).toEqual(['pilgrim-shell-' + v]);
    expect(await page.evaluate(n => caches.open(n).then(c => c.keys()).then(k => k.length), 'pilgrim-shell-' + v)).toBe(precacheCount(root));
    // first install must NOT reload the page (the worker claiming the page is not an update)
    await page.waitForTimeout(1500);
    expect(navs, 'page navigated more than once while the worker installed').toBe(1);

    await server.stop(); // no signal
    await page.reload();
    await ready(page);
    expect(await page.evaluate(() => [typeof window.Quill, typeof window.DOMPurify, typeof window.jspdf, typeof window.mammoth])).toEqual(['function', 'function', 'object', 'object']);
    await page.evaluate(() => { window.navTo('read'); document.getElementById('read-trans').value = 'kjv'; document.getElementById('read-ref').value = 'John 3'; return window.fetchReadChapter(); });
    await expect(page.locator('#read-display')).toContainText('zz-john-16');
    await page.evaluate(() => window.createFromTemplate('blank'));
    await expect(page.locator('.ql-editor').first()).toBeAttached();
    // tapping the icon = a fresh visit to the start URL with the server down
    await page.goto('/');
    await ready(page);
    expect(errors, errors.join('\n')).toEqual([]);
  });

  test('update: a new release waits, the banner shows, Refresh Now activates it with one reload, the old cache goes; Skip keeps it away', async ({ browser }) => {
    const { page, server, root, errors } = await open(browser);
    await page.goto('/index.html');
    await ready(page);
    await controlled(page);
    const v1 = versionOf(root);
    await expect(page.locator('#nav-version-display')).toHaveText('v' + v1);

    const { next: v2 } = shipNewRelease(root);
    await page.evaluate(() => navigator.serviceWorker.getRegistration().then(r => r.update()));
    await expect(page.locator('#update-banner')).toHaveClass(/\bon\b/, { timeout: 15000 });
    // installed in the background: both shells exist, the page still runs the OLD version, and the old worker still controls it
    await expect.poll(() => shellCaches(page)).toEqual(['pilgrim-shell-' + v1, 'pilgrim-shell-' + v2].sort());
    await expect(page.locator('#nav-version-display')).toHaveText('v' + v1);

    // Skip hides it and remembers that exact version; a new boot does not bring it back
    await page.click('#update-banner button:not(.primary)');
    await expect(page.locator('#update-banner')).not.toHaveClass(/\bon\b/);
    expect(await page.evaluate(() => localStorage.getItem('bsn_update_skip'))).toBe(v2);
    await page.reload();
    await ready(page);
    await page.waitForTimeout(1500);
    await expect(page.locator('#update-banner')).not.toHaveClass(/\bon\b/);

    // forget the skip, show the banner again, and press Refresh Now: exactly one reload, onto v2
    await page.evaluate(() => localStorage.removeItem('bsn_update_skip'));
    await page.reload();
    await ready(page);
    await expect(page.locator('#update-banner')).toHaveClass(/\bon\b/, { timeout: 15000 });
    let navs = 0;
    page.on('framenavigated', f => { if (f === page.mainFrame()) navs++; });
    await page.click('#update-banner button.primary');
    await expect(page.locator('#nav-version-display')).toHaveText('v' + v2, { timeout: 15000 });
    await ready(page);
    await controlled(page);
    await page.waitForTimeout(1500);
    expect(navs, 'Refresh Now must reload exactly once').toBe(1);
    expect(await shellCaches(page)).toEqual(['pilgrim-shell-' + v2]);
    // and it opens offline on the new version
    await server.stop();
    await page.reload();
    await ready(page);
    await expect(page.locator('#nav-version-display')).toHaveText('v' + v2);
    expect(errors, errors.join('\n')).toEqual([]);
  });

  test('kill flag true removes the worker and shell caches but never packs, localStorage, pilgrim-fonts or other apps; false brings it back', async ({ browser }) => {
    const { page, root, errors } = await open(browser);
    await page.goto('/index.html');
    await ready(page);
    await controlled(page);
    await installFake(page);
    await page.evaluate(() => {
      localStorage.setItem('bsn_qa_marker', 'keep-me');
      return caches.open('pilgrim-fonts').then(c => c.put('/font-x', new Response('f'))).then(() => caches.open('arche-scribe-v1')).then(c => c.put('/scribe-x', new Response('s')));
    });

    fs.writeFileSync(path.join(root, 'sw-kill.json'), '{"kill": true}');
    await page.reload();
    await expect.poll(() => regCount(page), { timeout: 20000 }).toBe(0);
    await ready(page);
    await page.waitForTimeout(1500);
    expect(await regCount(page)).toBe(0);                        // and it did not come back (no reload loop, no re-register)
    expect(await shellCaches(page)).toEqual([]);
    expect((await cacheNames(page)).sort()).toEqual(['arche-scribe-v1', 'pilgrim-fonts']);
    expect(await page.evaluate(() => localStorage.getItem('bsn_qa_marker'))).toBe('keep-me');
    const read = await page.evaluate(() => window.getBibleAPI('John 3:16', 'kjv').then(x => x, e => 'ERR ' + e));
    expect(read).toBe('[16] zz-john-16');                        // the IndexedDB pack is untouched
    expect(await page.evaluate(() => document.getElementById('scr-library').classList.contains('on'))).toBe(true);

    fs.writeFileSync(path.join(root, 'sw-kill.json'), '{"kill": false}');
    await page.reload();
    await controlled(page);
    expect((await shellCaches(page)).length).toBe(1);
    expect(errors, errors.join('\n')).toEqual([]);
  });

  test('kill layer 2: even when the page cannot read the flag, the worker deletes its own shell caches on the next visit', async ({ browser }) => {
    const { page, root } = await open(browser);
    await page.goto('/index.html');
    await ready(page);
    await controlled(page);
    // the page's own look at sw-kill.json says "not killed" (page requests only; the worker's own fetch sees the real file)
    await page.route(u => /sw-kill/.test(new URL(u.href).pathname), r => r.fulfill({ status: 200, contentType: 'application/json', body: '{"kill": false}' }));
    fs.writeFileSync(path.join(root, 'sw-kill.json'), '{"kill": true}');
    await page.reload();
    // the worker deleted its own shell caches (the page did not: its flag read said "not killed")...
    await expect.poll(() => shellCaches(page), { timeout: 20000 }).toEqual([]);
    // (the worker's own unregister() call returns true; the browser keeps listing a registration while a page it controls is
    // open, so what a test can observe reliably is the cache deletion)
  });

  test('Settings > Offline app: Turn off removes the worker and caches and stays off across reloads; Turn on brings it back', async ({ browser }) => {
    const { page, errors } = await open(browser);
    await page.goto('/index.html');
    await ready(page);
    await controlled(page);
    await page.evaluate(() => window.navTo('settings'));
    await expect(page.locator('#offline-app-status')).toContainText('On.');
    await page.click('#offline-app-btn');
    await expect(page.locator('#offline-app-status')).toContainText('Off.', { timeout: 10000 });
    expect(await page.evaluate(() => localStorage.getItem('bsn_offline_app'))).toBe('off');
    await expect.poll(() => regCount(page)).toBe(0);
    expect(await shellCaches(page)).toEqual([]);

    await page.reload();
    await ready(page);
    await page.waitForTimeout(2000);
    expect(await regCount(page), 'turned off, it must not register again on the next boot').toBe(0);
    await page.evaluate(() => window.navTo('settings'));
    await expect(page.locator('#offline-app-status')).toContainText('Off.');

    await page.click('#offline-app-btn');
    await expect(page.locator('#offline-app-status')).toContainText('On.', { timeout: 20000 });
    expect(await page.evaluate(() => localStorage.getItem('bsn_offline_app'))).toBeNull();
    expect((await shellCaches(page)).length).toBe(1);
    expect(errors, errors.join('\n')).toEqual([]);
  });

  test('boot cleanup removes only the legacy cache; our shell, pilgrim-fonts and another app\'s worker and caches stay', async ({ browser }) => {
    const { page, errors } = await open(browser);
    await page.goto('/index.html');
    await ready(page);
    await controlled(page);
    await page.evaluate(() => navigator.serviceWorker.register('/scribe/sw.js', { scope: '/scribe/' }));
    await page.waitForFunction(() => navigator.serviceWorker.getRegistrations().then(r => r.length === 2));
    await page.evaluate(() => Promise.all(['arche-pilgrim-v1', 'arche-scribe-v1', 'arche-pilgrim-v2-maintenance', 'pilgrim-fonts'].map(n => caches.open(n).then(c => c.put('/x', new Response('x'))))));
    await page.reload(); // boot cleanup finds the legacy cache and reloads once
    await ready(page);
    await controlled(page);
    await page.waitForTimeout(1000);
    const names = (await cacheNames(page)).sort();
    expect(names.filter(n => n.indexOf('pilgrim-shell-') === 0).length).toBe(1);
    expect(names.filter(n => n.indexOf('pilgrim-shell-') !== 0)).toEqual(['arche-pilgrim-v2-maintenance', 'arche-scribe-v1', 'pilgrim-fonts']);
    expect(await regCount(page)).toBe(2);
    expect(errors, errors.join('\n')).toEqual([]);
  });

  test('a fresh PIN entry with no connection says it needs a connection once', async ({ browser }) => {
    const { page, ctx, server } = await open(browser, { pin: true });
    await page.goto('/index.html');
    await page.waitForFunction(() => document.getElementById('pin-gate-overlay') && document.getElementById('pin-gate-overlay').classList.contains('on'));
    await controlled(page);
    await server.stop();
    await ctx.setOffline(true);
    await page.fill('#pin-input', '1234');
    await page.click('#pin-submit-btn');
    await expect(page.locator('#pin-error')).toContainText('offline');
  });
});
